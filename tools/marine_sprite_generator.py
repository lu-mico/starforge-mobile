#!/usr/bin/env python3
"""
Export the marine sprite set in Starforge-mobile's own delivery format
(per docs/ASSET_OUTSOURCING_BRIEF.md §2.1 / §3).

  assets/sprites/marine/marine_sheet_strip13.png     416x32 horizontal sheet (engine-ready)
  assets/sprites/marine/marine_sheet_grid4x4.png     131x131 grid (review sheet, 1px gutters)
  assets/sprites/marine/marine_<state>_<index>.png  13 individual frames (32x32)
  assets/sprites/marine/marine_frames.md             frame table
  assets/sprites/marine/marine_frames.json           machine-readable frame table
  tools/marine_sprite_sheet.py                       drawing module (source of truth)
  tools/marine_sprite_generator.py                   this script (one-command regeneration)

Usage:  python3 export_marine_assets.py [REPO_PATH]
"""
import json
import os
import shutil
import sys

from PIL import Image

import marine_sprite_sheet as M

CELL = M.CELL
FPS = {"idle": 2, "walk": 6, "attack": 8, "death": 4}
LOOP = {"idle": True, "walk": True, "attack": False, "death": False}


def cell_image(g):
    g.outline()
    return g.to_image()


def export(repo):
    out_dir = os.path.join(repo, "assets", "sprites", "marine")
    tools_dir = os.path.join(repo, "tools")
    os.makedirs(out_dir, exist_ok=True)
    os.makedirs(tools_dir, exist_ok=True)

    cs = M.build_frames()
    frames = []
    for i, (state, idx) in enumerate(M.FRAME_SPEC):
        name = f"marine_{state}_{idx}"
        cell_image(cs[i]).save(os.path.join(out_dir, name + ".png"))
        frames.append({
            "index": i, "name": name, "state": state, "state_index": idx,
            "x": i * CELL, "y": 0, "w": CELL, "h": CELL,
            "fps": FPS[state], "loop": LOOP[state],
        })

    strip = Image.new("RGBA", (CELL * 13, CELL), (0, 0, 0, 0))
    for i in range(13):
        strip.alpha_composite(cell_image(cs[i]), (i * CELL, 0))
    strip.save(os.path.join(out_dir, "marine_sheet_strip13.png"))

    grid = M.build_sheet(cs)
    grid.save(os.path.join(out_dir, "marine_sheet_grid4x4.png"))

    meta = {
        "unit": "marine",
        "canvas": [CELL, CELL],
        "strip": "marine_sheet_strip13.png",
        "strip_size": [CELL * 13, CELL],
        "grid": "marine_sheet_grid4x4.png",
        "grid_size": list(grid.size),
        "frames": frames,
        "palette": {k: "#%02X%02X%02X" % v for k, v in M.PAL.items() if v},
        "colors_used": 14,
        "alpha": "0 or 255 only (no feathered edges, no anti-aliasing)",
        "origin": "deterministically generated by code (NOT AI-generated, NOT human-commissioned)",
    }
    with open(os.path.join(out_dir, "marine_frames.json"), "w") as f:
        json.dump(meta, f, indent=2)

    md = ["# Marine — sprite sheet (13 frames)\n",
          "| 项 | 值 |", "|---|---|",
          "| 单位 | Marine（朝右 +X，左向由引擎 flip_h） |",
          "| 帧数 | 13 = idle 2 / walk 4 / attack 3 / death 4 |",
          "| 单帧画布 | 32×32，透明背景 |",
          "| 横向 sheet | `marine_sheet_strip13.png`（416×32，无间距，帧 i 的 x = i×32） |",
          "| 4×4 审阅图 | `marine_sheet_grid4x4.png`（131×131，1px 透明沟） |",
          "| 单帧 | `marine_<state>_<index>.png` ×13 |",
          "| 调色板 | 14 色（见 `marine_frames.json`） |",
          "| 抗锯齿 | 无（alpha 只含 0/255） |",
          "| 来源 | **确定性代码绘制**，非 AI 生成、非真人委托 |",
          "", "## 帧表（横向 sheet 顺序）\n",
          "| # | 文件 | 状态 | x | y | fps | loop |", "|---|---|---|---|---|---|---|"]
    for fr in frames:
        md.append(f"| {fr['index']} | `{fr['name']}.png` | {fr['state']} {fr['state_index']} | "
                  f"{fr['x']} | {fr['y']} | {fr['fps']} | {'yes' if fr['loop'] else 'no'} |")
    md += ["",
           "## Godot 4.6 导入提示\n",
           "- 用 `AnimatedSprite2D` + `SpriteFrames`；贴图 `marine_sheet_strip13.png`，",
           "  `hframes = 13`，`vframes = 1`，第 i 帧对应上表 x = i×32。",
           "- 建议用 `SpriteFrames` 分段：idle = 帧 0-1，walk = 2-5，attack = 6-8，death = 9-12。",
           "- 项目已设 `default_texture_filter = 0`（Nearest），移动端 2x 放大请用整数倍。",
           "", "## 验收对照（brief §3）\n",
           "- [x] 像素网格对齐，无抗锯齿、无半透明羽化边",
           "- [x] 13 帧轮廓比例一致（idle→death 不缩水）",
           "- [x] 透明背景 PNG-32，帧间距 0px（≤2px）",
           "- [x] 命名规范 `<unit>_<state>_<index>.png` + 帧表",
           "- [ ] Godot 4.6 导入测试通过 —— **待 Nagi 实跑确认**",
           "- [x] 声明「非 AI 生成」（确定性代码绘制）→ 商店审核披露最简",
           "- [x] 源文件：生成器 `tools/marine_sprite_generator.py`（可改色/改姿势重跑）",
           "", "## 重生成\n", "```bash", "python3 tools/marine_sprite_generator.py", "```"]
    with open(os.path.join(out_dir, "marine_frames.md"), "w") as f:
        f.write("\n".join(md) + "\n")

    # source of truth: the drawing module + this generator, side by side in tools/
    here = os.path.dirname(os.path.abspath(__file__))
    module_src = os.path.join(here, "marine_sprite_sheet.py")
    module_dst = os.path.join(tools_dir, "marine_sprite_sheet.py")
    if os.path.abspath(module_src) != os.path.abspath(module_dst):
        shutil.copy2(module_src, module_dst)
    gen_dst = os.path.join(tools_dir, "marine_sprite_generator.py")
    if os.path.abspath(__file__) != os.path.abspath(gen_dst):
        shutil.copy2(__file__, gen_dst)
    return out_dir


def main():
    if len(sys.argv) > 1:
        repo = sys.argv[1]
    else:
        # when this script lives in <repo>/tools/, default to <repo>
        repo = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
    out = export(repo)
    print("exported ->", out)


if __name__ == "__main__":
    main()
