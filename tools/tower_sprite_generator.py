#!/usr/bin/env python3
"""
Regenerate the tower sprites into <repo>/assets/sprites/towers/.

    python3 tools/tower_sprite_generator.py [REPO_PATH]

brief §2.2: player / enemy / king tower, each intact + damaged = 6 images,
40x60, transparent background, hard edges, shared 16-colour palette.
"""
import json
import os
import sys

HERE = os.path.dirname(os.path.abspath(__file__))
sys.path.insert(0, HERE)

from PIL import Image

import marine_sprite_sheet as M
import tower_sprite_sheet as T
from sprite_export import verify_exports

FPS = {}
LOOP = {}


def main():
    repo = sys.argv[1] if len(sys.argv) > 1 else os.path.dirname(HERE)
    out = os.path.join(repo, "assets", "sprites", "towers")
    os.makedirs(out, exist_ok=True)

    images = T.build_images()
    frames = []
    for i, (name, img) in enumerate(images):
        img.save(os.path.join(out, name + ".png"))
        frames.append({"index": i, "name": name, "state": name, "state_index": i,
                       "x": i * T.W, "y": 0, "w": T.W, "h": T.H, "fps": 0, "loop": False})

    # review strip (6 wide) and 3x2 review grid, 1px transparent gutters
    strip = Image.new("RGBA", (T.W * len(images), T.H), (0, 0, 0, 0))
    for i, (_, img) in enumerate(images):
        strip.alpha_composite(img, (i * T.W, 0))
    strip.save(os.path.join(out, "towers_sheet_strip6.png"))

    cols, rows = 3, 2
    gut = 1
    grid = Image.new("RGBA", (cols * T.W + (cols - 1) * gut, rows * T.H + (rows - 1) * gut),
                     (0, 0, 0, 0))
    for i, (_, img) in enumerate(images):
        grid.alpha_composite(img, ((i % cols) * (T.W + gut), (i // cols) * (T.H + gut)))
    grid.save(os.path.join(out, "towers_sheet_grid3x2.png"))

    meta = {
        "unit": "towers",
        "canvas": [T.W, T.H],
        "strip": "towers_sheet_strip6.png",
        "strip_size": [T.W * len(images), T.H],
        "grid": "towers_sheet_grid3x2.png",
        "grid_size": list(grid.size),
        "frames": frames,
        "palette": {k: "#%02X%02X%02X" % v for k, v in M.PAL.items() if v},
        "colors_used": 14,
        "alpha": "0 or 255 only (no feathered edges, no anti-aliasing)",
        "origin": "deterministically generated by code (NOT AI-generated, NOT human-commissioned)",
        "note": "static art (no animation): each image is a separate tower+state",
    }
    with open(os.path.join(out, "towers_frames.json"), "w") as f:
        json.dump(meta, f, indent=2)


    # human-readable twin of the JSON (same delivery shape as the unit batches)
    lines = ["# Towers — sprite set (6 static images)\n",
             "| 项 | 值 |", "|---|---|",
             "| 画布 | 40x60，透明背景 |",
             "| 数量 | 6（玩家塔 / 敌方塔 / 王塔 × 完好 / 受击） |",
             "| 调色板 | 14 色（见 `towers_frames.json`） |",
             "| 抗锯齿 | 无（alpha 只含 0/255） |",
             "| 来源 | **确定性代码绘制**，非 AI 生成、非真人委托 |",
             "", "## 清单\n",
             "| # | 文件 | 状态 | 尺寸 |", "|---|---|---|---|"]
    for fr in frames:
        lines.append(f"| {fr['index']} | `{fr['name']}.png` | {fr['state']} | {fr['w']}x{fr['h']} |")
    lines += ["", "## 验收对照（brief §3）\n",
              "- [x] 像素网格对齐，无抗锯齿、无半透明羽化边",
              "- [x] 透明背景 PNG-32",
              "- [x] 命名规范 `<subject>_<state>.png` + 清单",
              "- [x] **三处导出像素一致**（单张 == strip 格 == grid 格）由 `verify_exports()` 硬校验",
              "- [x] Godot 4.6 导入测试通过 —— `tools/accept_static_sprites.gd` **24/24 PASS**（4.6.stable.official.89cea1439）",
              "- [x] 声明「非 AI 生成」（确定性代码绘制）→ 商店审核披露最简",
              "", "## 重生成\n", "```bash", "python3 tools/tower_sprite_generator.py", "```"]
    with open(os.path.join(out, "towers_frames.md"), "w") as f:
        f.write("\n".join(lines) + "\n")

    n = verify_exports(out, "towers", T.W, len(images), cell_h=T.H)
    print("towers: %d sprites exported + verified" % n)


if __name__ == "__main__":
    main()
